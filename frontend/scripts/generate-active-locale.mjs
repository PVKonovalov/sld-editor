#!/usr/bin/env node
// Writes src/i18n/active.ts to re-export whichever locale's dictionary
// (src/i18n/<locale>.ts) was requested. i18n is picked at *build time*
// here, not switched at runtime: the app only ever imports './active',
// never a specific locale directly, so an unselected locale's strings
// never reach the bundle. Re-run by every dev/build/dev:ru/build:ru
// script in package.json — never edit src/i18n/active.ts by hand, it's
// overwritten on the next run.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const SUPPORTED_LOCALES = ['en', 'ru']

const locale = process.argv[2]
if (!SUPPORTED_LOCALES.includes(locale)) {
  console.error(`generate-active-locale: unknown locale "${locale}" — expected one of: ${SUPPORTED_LOCALES.join(', ')}`)
  process.exit(1)
}

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const outPath = path.join(scriptDir, '..', 'src', 'i18n', 'active.ts')

const contents = `// AUTO-GENERATED by scripts/generate-active-locale.mjs ${locale} — do not edit
// by hand, it's overwritten on the next dev/build run. See that script's
// own doc comment.
export { dictionary } from './${locale}'
export type { Dictionary } from './en'
`

writeFileSync(outPath, contents)
console.log(`generate-active-locale: active locale set to "${locale}" (src/i18n/active.ts)`)
